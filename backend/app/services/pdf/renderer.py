"""Templated PDF export via WeasyPrint.

HTML construction is separated from PDF conversion so templates can be unit
tested without the (heavy) WeasyPrint dependency installed.
"""
from __future__ import annotations

import base64
import html
import io
from datetime import datetime

from jinja2 import Environment, select_autoescape

DEFAULT_TEMPLATE_CONFIG = {
    "accent": "#4f46e5",
    "font": "Helvetica, Arial, sans-serif",
    "include_one_liner": True,
    "include_summary": True,
    "include_takeaways": True,
    "include_insights": True,
    "include_entities": True,
    "include_transcript": True,
    "include_qr": True,
    "title": "ReelVault Export",
}

_env = Environment(autoescape=select_autoescape(["html"]))

_BASE_CSS = """
@page { size: A4; margin: 1.6cm; }
* { box-sizing: border-box; }
body { font-family: {{ cfg.font }}; color: #1f2430; font-size: 11pt; line-height: 1.5; }
h1 { font-size: 20pt; margin: 0 0 2pt; color: {{ cfg.accent }}; }
h2 { font-size: 13pt; margin: 18pt 0 4pt; border-bottom: 2px solid {{ cfg.accent }}22; padding-bottom: 3pt; }
h3 { font-size: 12pt; margin: 14pt 0 2pt; }
.meta { color: #6b7280; font-size: 9.5pt; margin-bottom: 6pt; }
.oneliner { font-size: 12pt; font-style: italic; color: #374151; margin: 6pt 0 10pt; }
.tag { display: inline-block; background: {{ cfg.accent }}14; color: {{ cfg.accent }};
       border-radius: 10px; padding: 1pt 8pt; font-size: 8.5pt; margin: 0 4pt 4pt 0; }
ul { margin: 4pt 0 8pt 16pt; padding: 0; }
.transcript { white-space: pre-wrap; background: #f7f7f9; border: 1px solid #ececf1;
              border-radius: 6px; padding: 8pt; font-size: 9pt; color: #374151; }
.reel { page-break-inside: avoid; margin-bottom: 20pt; padding-bottom: 8pt; border-bottom: 1px solid #ececf1; }
.url { color: {{ cfg.accent }}; font-size: 9pt; word-break: break-all; }
.cover { text-align:center; margin-bottom: 24pt; }
.qr { float: right; width: 90px; height: 90px; }
.footer { color:#9ca3af; font-size: 8pt; text-align:center; margin-top: 18pt; }
"""

_REEL_BLOCK = """
<div class="reel">
  {% if qr %}<img class="qr" src="{{ qr }}"/>{% endif %}
  <h3>{{ reel.title or 'Untitled Reel' }}</h3>
  <div class="meta">
    {% if reel.creator_username %}@{{ reel.creator_username }} · {% endif %}
    {% if reel.shared_at %}shared {{ reel.shared_at }} · {% endif %}
    status: {{ reel.processing_status }}
  </div>
  {% if reel.category %}<span class="tag">{{ reel.category }}</span>{% endif %}
  {% for s in (reel.subcategories or []) %}<span class="tag">{{ s }}</span>{% endfor %}
  {% if cfg.include_one_liner and reel.one_liner %}<div class="oneliner">{{ reel.one_liner }}</div>{% endif %}
  {% if cfg.include_summary and reel.summary %}<h4>Summary</h4><div>{{ reel.summary }}</div>{% endif %}
  {% if cfg.include_takeaways and reel.key_takeaways %}
    <h4>Key takeaways</h4><ul>{% for t in reel.key_takeaways %}<li>{{ t }}</li>{% endfor %}</ul>{% endif %}
  {% if cfg.include_insights and reel.actionable_insights %}
    <h4>Actionable insights</h4><ul>{% for t in reel.actionable_insights %}<li>{{ t }}</li>{% endfor %}</ul>{% endif %}
  {% if cfg.include_entities and reel.entities %}
    <h4>Entities</h4><div>{% for e in reel.entities %}<span class="tag">{{ e }}</span>{% endfor %}</div>{% endif %}
  <div class="url">{{ reel.normalized_url }}</div>
  {% if cfg.include_transcript and reel.transcript %}
    <h4>Transcript</h4><div class="transcript">{{ reel.transcript }}</div>{% endif %}
</div>
"""

_DOC = """<!DOCTYPE html><html><head><meta charset="utf-8"><style>{{ css }}</style></head>
<body>
  <div class="cover"><h1>{{ heading }}</h1><div class="meta">{{ subtitle }}</div></div>
  {{ body }}
  <div class="footer">Generated by ReelVault · {{ generated_at }}</div>
</body></html>"""


def _maybe_qr(url: str, enabled: bool) -> str | None:
    if not enabled:
        return None
    try:
        import qrcode

        img = qrcode.make(url)
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    except Exception:
        return None


def _reel_view(reel) -> dict:
    return {
        "title": reel.title,
        "creator_username": reel.creator_username,
        "shared_at": reel.shared_at.strftime("%Y-%m-%d") if reel.shared_at else None,
        "processing_status": reel.processing_status,
        "category": reel.category,
        "subcategories": reel.subcategories or [],
        "one_liner": reel.one_liner,
        "summary": reel.summary,
        "key_takeaways": reel.key_takeaways or [],
        "actionable_insights": reel.actionable_insights or [],
        "entities": reel.entities or [],
        "normalized_url": reel.normalized_url,
        "transcript": reel.transcript,
    }


def _merge_cfg(config: dict | None) -> dict:
    cfg = dict(DEFAULT_TEMPLATE_CONFIG)
    if config:
        cfg.update({k: v for k, v in config.items() if v is not None})
    return cfg


def build_html(*, heading: str, subtitle: str, reels: list, config: dict | None) -> str:
    cfg = _merge_cfg(config)
    css = _env.from_string(_BASE_CSS).render(cfg=cfg)
    blocks = []
    tmpl = _env.from_string(_REEL_BLOCK)
    for reel in reels:
        rv = _reel_view(reel)
        qr = _maybe_qr(rv["normalized_url"], cfg["include_qr"])
        blocks.append(tmpl.render(reel=rv, cfg=cfg, qr=qr))
    body = "\n".join(blocks)
    return _env.from_string(_DOC).render(
        css=css,
        heading=html.escape(heading),
        subtitle=html.escape(subtitle),
        body=body,
        generated_at=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
    )


def html_to_pdf(html_str: str) -> bytes:
    from weasyprint import HTML  # lazy import — heavy dependency

    return HTML(string=html_str).write_pdf()


def reel_pdf(reel, config: dict | None = None) -> bytes:
    cfg = _merge_cfg(config)
    html_str = build_html(
        heading=reel.title or "Reel", subtitle=cfg.get("title", "ReelVault Export"),
        reels=[reel], config=cfg,
    )
    return html_to_pdf(html_str)


def collection_pdf(title: str, reels: list, config: dict | None = None) -> bytes:
    html_str = build_html(
        heading=title, subtitle=f"{len(reels)} reels", reels=reels, config=config,
    )
    return html_to_pdf(html_str)
